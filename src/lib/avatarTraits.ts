const FALLBACK_TRAITS: AvatarTraits = {
  hair: 'Short dark crop',
  eyes: 'Dark anime eyes',
  outfit: 'Plain adventurer tunic and boots',
  props: 'None',
  aura: 'None',
}

/** Traits for a catalog id, falling back to a neutral set for unknown ids. */
export function avatarTraits(characterId: string): AvatarTraits {
  return AVATAR_TRAITS[characterId] ?? FALLBACK_TRAITS
}

/** Identity bullets for sequential animation prompts (internal). */
export function avatarIdentityPromptLines(id: string | null | undefined): string[] {
  const meta = getAvatarCharacterMeta(id) ?? getAvatarCharacterMeta(DEFAULT_AVATAR_ID)!
  const traits = avatarTraits(meta.id)
  return [
    `${meta.name} (inspired by ${meta.inspirationSeries} / ${meta.inspirationCharacter})`,
    traits.hair,
    traits.eyes,
    traits.outfit,
    traits.props,
    traits.aura,
  ]
}
