#!/usr/bin/env node
/**
 * Bundle the owner-only private files into the `private-files` Edge Function.
 *
 * Reads the allowlisted files from supabase/functions/private-files/files/
 * and writes supabase/functions/private-files/files.generated.ts (base64 of gzip).
 * Both the files folder contents and the generated module are gitignored.
 *
 * Usage: node scripts/build-private-files.mjs
 * Then:  npx supabase functions deploy private-files --project-ref <ref> --no-verify-jwt
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import zlib from 'node:zlib'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const fnDir = path.join(root, 'supabase', 'functions', 'private-files')
const filesDir = path.join(fnDir, 'files')
const outFile = path.join(fnDir, 'files.generated.ts')

// Keep in sync with ALLOWED_FILES in supabase/functions/private-files/handler.ts
// (src/lib/privateFiles.test.ts enforces this).
export const PRIVATE_FILE_NAMES = ['download.py', 'ids.txt']

const entries = {}
for (const name of PRIVATE_FILE_NAMES) {
  const p = path.join(filesDir, name)
  if (!fs.existsSync(p)) {
    console.warn(`missing (skipped): ${path.relative(root, p)}`)
    continue
  }
  const buf = fs.readFileSync(p)
  entries[name] = zlib.gzipSync(buf, { level: 9 }).toString('base64')
  console.log(`bundled ${name} (${buf.length} bytes)`)
}

const body =
  '// GENERATED by scripts/build-private-files.mjs — do not edit, do not commit.\n' +
  'export const PRIVATE_FILES: Readonly<Record<string, string>> = ' +
  JSON.stringify(entries, null, 2) +
  ';\n'
fs.writeFileSync(outFile, body)
console.log(`wrote ${path.relative(root, outFile)}`)
